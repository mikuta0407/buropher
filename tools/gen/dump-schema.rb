# Redmine 6.1.2 のコアテーブル定義(列名・論理型)と schema_migrations を Go ソースとして出力する。
# internal/redmineimport/export/schema_gen.go の生成元。
# 使い方: cd <redmine(マイグレーション直後・プラグインなし)> &&
#   SECRET_KEY_BASE=x RAILS_ENV=production bin/rails runner <this file> > schema_gen.go && gofmt -w schema_gen.go
conn = ActiveRecord::Base.connection
skip = %w[schema_migrations ar_internal_metadata]
tables = conn.tables.sort - skip
versions = conn.select_values("SELECT version FROM schema_migrations")
core = versions.grep(/\A\d+\z/).sort_by { |v| [v.length, v] }

puts "// SPDX-License-Identifier: GPL-2.0-or-later\n// Copyright (C) 2026 mikuta0407 and Buropher contributors\n"
puts "// Code generated by tools/gen/dump-schema.rb; DO NOT EDIT."
puts
puts "package export"
puts
puts "// coreTables は Redmine 6.1.2 のコア業務テーブル(#{tables.size} 個)と各列の論理型。"
puts "// 型は ActiveRecord の型シンボル(integer/string/text/boolean/datetime/date/float/binary/decimal)。"
puts "var coreTables = []tableDef{"
tables.each do |t|
  pk = conn.primary_key(t)
  puts "\t{Name: #{t.to_json}, PK: #{(pk || '').to_json}, Columns: []columnDef{"
  conn.columns(t).each do |c|
    puts "\t\t{Name: #{c.name.to_json}, Type: #{c.type.to_s.to_json}},"
  end
  puts "\t}},"
end
puts "}"
puts
puts "// coreMigrations は Redmine 6.1.2 で db:migrate 後に得られるコア schema_migrations(#{core.size} 件)。"
puts "var coreMigrations = []string{"
core.each_slice(8) { |s| puts "\t" + s.map(&:to_json).join(", ") + "," }
puts "}"
